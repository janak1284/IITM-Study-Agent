"""
gemini_web_automator.py

Option B: Gemini 3.1 Pro Web UI Automator via Playwright (Chrome CDP)

What this script does:
1. Connects to your running Chrome instance on `http://127.0.0.1:9223` (where you are logged into Gemini).
2. Opens `https://gemini.google.com/app` in a new tab.
3. Automatically pastes the weekly prompt (`prompts_for_gemini/<Course>/<Week>_prompt.md`).
4. Submits the prompt to Gemini 3.1 Pro and intelligently waits for the full response to finish generating.
5. Saves the output note straight into your Obsidian Vault (`OBSIDIAN_VAULT_DIR`).
6. Uses Playwright headless HTML->PDF rendering to export a beautifully styled `.pdf` alongside the `.md` note.


Usage:
    # Run for a specific course & week:
    python gemini_web_automator.py --course "May 2026 - BDM" --week "Week 1"

    # Or run across all weeks sequentially:
    python gemini_web_automator.py
"""

